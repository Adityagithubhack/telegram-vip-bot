    value = TRANSLATIONS.get(language, {}).get(key)

    if value is None:
        value = TRANSLATIONS["en"].get(key, key)

    settings = get_settings()

    value = value.replace(
        "SPIDY SPORTS INTELLIGENCE",
        settings.brand_name,
    ).replace(
        "SPIDY’S ADMIN",
        settings.admin_brand_name,
    )

    if kwargs:
        return value.format(**kwargs)

    return value

